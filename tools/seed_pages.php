    'title' => 'আমাদের সম্পর্কে জানুন',
    'meta'  => '{STORE} — নির্ভরযোগ্য ও সহজ অনলাইন কেনাকাটার বিশ্বস্ত মাধ্যম',
    'html'  => $about,
  ],
  'privacy' => [
    'title' => 'গোপনীয়তা নীতি (Privacy Policy)',
    'meta'  => '{STORE} — আপনার তথ্যের সুরক্ষা আমাদের প্রথম অগ্রাধিকার',
    'html'  => $privacy,
  ],
  'terms'   => [
    'title' => 'শর্তাবলী (Terms & Conditions)',
    'meta'  => '{STORE} — কেনাকাটা করার আগে নিয়মাবলী জেনে নিন',
    'html'  => $terms,
  ],
  'contact' => [
    'title' => 'যোগাযোগ করুন',
    'meta'  => 'যেকোনো প্রশ্ন, তথ্য বা সহায়তার জন্য আমাদের সাথে সরাসরি যোগাযোগ করুন',
    'html'  => $contact,
  ],
];

$sel = $pdo->prepare("SELECT id FROM pages WHERE slug=? LIMIT 1");
$ins = $pdo->prepare("INSERT INTO pages(slug,title,content,meta_description,active) VALUES(?,?,?,?,1)");
$upd = $pdo->prepare("UPDATE pages SET title=?, content=?, meta_description=?, active=1 WHERE slug=?");

foreach ($pages as $slug => $p) {
    $html  = $p['html'];
    $meta  = $p['meta'];

    $sel->execute([$slug]);
    $id = $sel->fetchColumn();

    if ($id) {
        $upd->execute([$p['title'], $html, $meta, $slug]);
        printf("UPDATED  %-8s #%d  %s (%d bytes)\n", $slug, $id, $p['title'], strlen($html));
    } else {
        $ins->execute([$slug, $p['title'], $html, $meta]);
        printf("INSERTED %-8s #%d  %s (%d bytes)\n", $slug, $pdo->lastInsertId(), $p['title'], strlen($html));
    }
}

echo "\n--- verify ---\n";
foreach ($pdo->query("SELECT id,slug,title,LENGTH(content) len,meta_description FROM pages ORDER BY id")->fetchAll() as $r) {
    printf("#%d %-8s %-32s %6d bytes  hero=%s\n",
        $r['id'], $r['slug'], $r['title'], (int)$r['len'], $r['meta_description']);
}

echo "\nDONE\n";
